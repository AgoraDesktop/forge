#!/usr/bin/env python3
"""Rasterise the vendored Tabler SVGs into a C header of RGBA tiles.

    embed-glyphs.py <icons-dir> <output-header> <rsvg-convert>

Each icon becomes two representations — 24 and 48 pixels square — because a toolbar's icon box is 24 points and a display
may want two device pixels per point. The output is one array per icon and a table of them, so the application reads a
GLYPH and an NSImage is built from its bytes; nothing is loaded from disk at run time.

Black is drawn as opaque and everything else as transparent: the toolbar inks a TEMPLATE image itself, which is what makes
a disabled button's icon the same grey as its label.
"""

import subprocess
import sys


def rasterise(rsvg, svg, size):
    """The four RGBA channels of one tile, as a list of ints."""
    ppm = subprocess.run(
        [rsvg, "-w", str(size), "-h", str(size), "-f", "png", svg],
        check=True, stdout=subprocess.PIPE).stdout
    # rsvg gives PNG, and this script must not depend on an image library: ask ImageMagick for PPM instead.
    return ppm


def tile(rsvg, svg, size):
    """RGBA bytes, via rsvg's vector path and ImageMagick's decoder."""
    png = subprocess.run([rsvg, "-w", str(size), "-h", str(size), svg],
                         check=True, stdout=subprocess.PIPE).stdout
    raw = subprocess.run(["convert", "png:-", "-depth", "8", "rgba:-"],
                         check=True, input=png, stdout=subprocess.PIPE).stdout
    return raw


def main():
    icons_dir, out_path, rsvg = sys.argv[1], sys.argv[2], sys.argv[3]
    names = ["hammer", "player-play", "trash", "square", "plus", "package-export", "file-minus"]
    sizes = [24, 48]
    lines = ["/* GENERATED by tools/embed-glyphs.py from assets/tabler-icons — do not edit. */",
             "#ifndef AGORA_TOOLBAR_GLYPHS_H", "#define AGORA_TOOLBAR_GLYPHS_H", ""]
    for name in names:
        ident = name.replace("-", "_")
        for size in sizes:
            data = tile(rsvg, f"{icons_dir}/{name}.svg", size)
            if len(data) != size * size * 4:
                raise SystemExit(f"{name} at {size}: {len(data)} bytes, expected {size * size * 4}")
            values = ",".join(str(b) for b in data)
            lines.append(f"static const unsigned char AGGlyph_{ident}_{size}[] = {{{values}}};")
        lines.append(f"static const unsigned char *AGGlyph_{ident}[2] = {{"
                     f"AGGlyph_{ident}_24, AGGlyph_{ident}_48}};")
        lines.append("")
    lines.append("#endif /* AGORA_TOOLBAR_GLYPHS_H */")
    with open(out_path, "w") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
